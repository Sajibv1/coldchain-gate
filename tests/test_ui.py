# -- the hand-written block -------------------------------------------------------------


def test_every_fixture_is_offered_by_the_page(page: str) -> None:
    """Every fixture the pipeline knows about needs a label, or it has no button."""
    for name in fixtures.FIXTURES:
        assert name in page, f"the page offers no indent for the {name!r} fixture"


def test_the_copy_labels_every_fixture(copy: dict[str, Any]) -> None:
    """The button list is driven by this block, so it has to be the whole set — both ways."""
    assert set(copy["fixtures"]) == set(fixtures.FIXTURES)


def test_the_copy_names_every_hold_code(copy: dict[str, Any]) -> None:
    """Every code in the closed set has a sentence, not just the ones the demo reaches.

    Checked against the enum rather than against the fixtures, so a code that is documented but
    not currently reachable still has to be explained, and a code invented in the page fails.
    """
    codes = {value for name, value in vars(HoldCode).items() if not name.startswith("_")}
    assert codes, "the enum read as empty — this test would pass on anything"
    assert set(copy["holds"]) == codes


# -- the page itself --------------------------------------------------------------------


def test_the_gate_column_names_the_real_allowlist(page: str) -> None:
    """The middle column is the page's central claim, so it is pinned to the type it cites.

    ``ALERT_FIELDS`` is derived from ``DispatchAlert``'s own field list, so renaming a field
    there renames it everywhere the boundary is enforced. The page names the four fields in
    markup the script then fills by key. If those two drift, the column renders four empty
    values and the page quietly stops demonstrating anything — so they are asserted equal
    rather than merely asserted to be four.
    """
    assert tuple(re.findall(r'data-field="([^"]+)"', page)) == ALERT_FIELDS


def test_the_script_reads_no_alert_field_that_cannot_cross(page: str) -> None:
    """A property read off ``alert`` that is not on the allowlist would render as undefined.

    The gate values are filled by key, so a typo here is not a crash — it is a blank where a
    value should be, on the one column whose job is to show that values do cross.
    """
    script = re.findall(r"<script>\n(.*?)\n</script>", page, re.DOTALL)[-1]
    props = set(re.findall(r"\ba\.([a-z_]+)", script)) | set(
        re.findall(r"alert\.([a-z_]+)", script)
    )
    assert props, "no alert property read — the regex or the script changed"
    assert props <= set(ALERT_FIELDS), f"the page reads fields that cannot cross: {props}"


def test_the_page_fetches_nothing_undocumented(page: str) -> None:
    """The page is static and same-origin; it must not reach anywhere else.

    A demo page that quietly called a third party would be a network egress the rest of this
    project is careful not to have, and it would be invisible in every other test.
    """
    fetched = set(re.findall(r'fetch\(\s*"([^"]+)"', page))
    assert fetched, "no fetch call found — the regex or the page changed"
    assert fetched <= {"/health", "/indent/demo/"}, (
        f"the page fetches something undocumented: {sorted(fetched)}"
    )


def test_the_page_loads_no_external_script(page: str) -> None:
    """It has to work from a filesystem path as well as from the server.

    The only external reference the page is allowed is the stylesheet's font, and that degrades
    to system fonts. A script with an ``src`` would not: a reviewer opening the file directly
    would get a page that looks finished and does nothing.
    """
    for tag in re.findall(r"<script[^>]*>", page):
        assert "src=" not in tag, f"the page loads a script it cannot guarantee: {tag}"
